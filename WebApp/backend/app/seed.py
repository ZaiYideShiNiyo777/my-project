def run() -> None:
    Base.metadata.create_all(bind=engine)
    db: Session = SessionLocal()
    try:
        if db.query(Category).first():
            print("分类数据已存在，跳过 seed（如需重置请先清空数据表）")
            return

        # 1. 分类
        for cid, name, icon in TOP_CATEGORIES:
            db.add(Category(id=cid, name=name, icon_name=icon, parent_id=0, sort_order=cid))
        for cid, name, pid in SUB_CATEGORIES:
            db.add(Category(id=cid, name=name, parent_id=pid, sort_order=cid))
        db.flush()

        # 2. 可信数据源
        source_by_domain: dict[str, TrustedSource] = {}
        for domain, name, industry_id, score in SOURCES:
            src = TrustedSource(
                domain=domain,
                source_name=name,
                industry_id=industry_id,
                trust_score=Decimal(score),
            )
            db.add(src)
            source_by_domain[domain] = src
        db.flush()

        # 3. 示例信息 + 分类关联（支持一条信息挂多个分类）
        now = datetime.utcnow()
        for title, summary, domain, score, cat_ids, hours_ago in ITEMS:
            item = InformationItem(
                title=title,
                summary=summary,
                source_url=f"https://www.{domain}/news/{abs(hash(title))}",
                source_id=source_by_domain[domain].id,
                credibility_score=Decimal(score),
                publish_time=now - timedelta(hours=hours_ago),
            )
            for cid in cat_ids:
                cat = db.get(Category, cid)
                if cat:
                    item.categories.append(cat)
            db.add(item)

        db.commit()
        print(
            f"Seed 完成：{len(TOP_CATEGORIES)} 个一级分类 + {len(SUB_CATEGORIES)} 个二级分类"
            f" + {len(SOURCES)} 个数据源 + {len(ITEMS)} 条信息"
        )
    except Exception:
        db.rollback()
        raise
    finally:
        db.close()


if __name__ == "__main__":
    run()
